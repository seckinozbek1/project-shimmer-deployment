def observe_key_and_twin():
    """The generated test scored by --key with its twin by --twin-key and --twin-run, and
    the twin scored by --key with the test as its twin."""
    with tempfile.TemporaryDirectory(prefix="shimmer_scorer_path_") as td:
        bundles, runs = fixture(td)
        planted = len(_key(bundles["test"])["planted"])
        status, lines = run_scorer(["--key", str(bundles["test"] / "answer_key.json"),
                                    "--run", str(runs["test"]),
                                    "--twin-key", str(bundles["twin"] / "answer_key.json"),
                                    "--twin-run", str(runs["twin"])])
        back, back_lines = run_scorer(["--key", str(bundles["twin"] / "answer_key.json"),
                                       "--run", str(runs["twin"]),
                                       "--twin-key", str(bundles["test"] / "answer_key.json"),
                                       "--twin-run", str(runs["test"])])
        alone, alone_lines = run_scorer(["--key", str(bundles["test"] / "answer_key.json"),
                                         "--run", str(runs["test"])])
        return {"planted": planted, "status": status,
                "recall": _line(lines, "recall          :"),
                "confirmed": _line(lines, "  recall, reason confirmed"),
                "twin": re.sub(r"\(([^()]*)\)\s*$", "(run)", _line(lines, "twin check")),
                "twin_status": back, "twin_recall": _line(back_lines, "recall          :"),
                "twin_back": re.sub(r"\(([^()]*)\)\s*$", "(run)", _line(back_lines, "twin check")),
                "alone_status": alone,
                "alone_twin": _line(alone_lines, "twin check").startswith("twin check      : not asked")}


def expected_key_and_twin(planted):
    return {"planted": planted, "status": 0,
            "recall": "recall          : %d/%d   (every planted entry, LOCATION ONLY)" % (planted, planted),
            "confirmed": "  recall, reason confirmed  : %d/%d   (THIS is the figure that says a defect was "
                         "actually detected)" % (planted, planted),
            "twin": "twin check      : 1 claim(s) worded identically in both twins (run)",
            "twin_status": 0, "twin_recall": "recall          : 0/0   (every planted entry, LOCATION ONLY)",
            "twin_back": "twin check      : 1 claim(s) worded identically in both twins (run)",
            "alone_status": 0, "alone_twin": True}


def observe_wrong_twin():
    """A twin key that is not the declared twin (a probe's), and a twin run that is a run
    of the test rather than of the twin: both refused."""
    with tempfile.TemporaryDirectory(prefix="shimmer_scorer_wrong_twin_") as td:
        bundles, runs = fixture(td)
        test_key = str(bundles["test"] / "answer_key.json")
        wrong_key, _ = run_scorer(["--key", test_key, "--run", str(runs["test"]),
                                   "--twin-key", str(bundles["probe"] / "answer_key.json"),
                                   "--twin-run", str(runs["twin"])])
        wrong_run, _ = run_scorer(["--key", test_key, "--run", str(runs["test"]),
                                   "--twin-key", str(bundles["twin"] / "answer_key.json"),
                                   "--twin-run", str(runs["test"])])
        half, _ = run_scorer(["--key", test_key, "--run", str(runs["test"]),
                              "--twin-key", str(bundles["twin"] / "answer_key.json")])
        return {"wrong_key": str(wrong_key).startswith("refused: the scored key's twin is"),
                "wrong_run": str(wrong_run).startswith("refused: ") and "is not a run of the twin" in str(wrong_run),
                "half": half == "refused: usage"}


WRONG_TWIN = {"wrong_key": True, "wrong_run": True, "half": True}


def _corpora_layout(root, bundles, runs):
    """benchmark/corpora/ and output/runs/ as the default path reads them, in a temporary
    root: each bundle under its own name, the twin's run under output/runs/."""
    corpora = Path(root) / "corpora"
    for name in ("test", "twin"):
        shutil.copytree(bundles[name], corpora / bundles[name].name)
    shutil.copytree(runs["twin"], Path(root) / "output" / "runs" / "2026-10-28__twin")
    return corpora


def observe_default_path():
    """--corpus <name> under a temporary corpora root, the twin's run found by name under a
    temporary output/runs/, as the scorer has always done."""
    sc = _scorer()
    with tempfile.TemporaryDirectory(prefix="shimmer_scorer_default_") as td:
        bundles, runs = fixture(td)
        corpora = _corpora_layout(Path(td) / "root", bundles, runs)
        with patch.object(sc, "CORPORA", corpora), patch.object(sc, "ROOT", Path(td) / "root"):
            status, lines = run_scorer(["--corpus", bundles["test"].name, "--run", str(runs["test"])])
        return {"status": status, "recall": _line(lines, "recall          :"),
                "twin": re.sub(r"\(([^()]*)\)\s*$", "(run)", _line(lines, "twin check"))}


def remote_scorer_flags():
    """The flags tools/cloud_run_remote.py passes to the scorer, read from its own source:
    the string constants of the list that names score_corpus.py."""
    tree = ast.parse(REMOTE.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.List) and any(
                "score_corpus.py" in ast.unparse(e) for e in node.elts):
            return [e.value for e in node.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
    return None


def observe_absolute_caller():
    """The remote caller's flags, run with an absolute bundle path, against the same
    bundle by name: the same figures."""
    sc = _scorer()
    flags = remote_scorer_flags()
    with tempfile.TemporaryDirectory(prefix="shimmer_scorer_absolute_") as td:
        bundles, runs = fixture(td)
        corpora = _corpora_layout(Path(td) / "root", bundles, runs)
        absolute = corpora / bundles["test"].name
        argv = [flags[0], str(absolute.resolve()), flags[1], str(runs["test"])] if flags and len(flags) == 2 else []
        with patch.object(sc, "CORPORA", corpora), patch.object(sc, "ROOT", Path(td) / "root"):
            by_path, path_lines = run_scorer(argv) if argv else ("no caller flags", [])
            by_name, name_lines = run_scorer(["--corpus", absolute.name, "--run", str(runs["test"])])
        return {"flags": flags, "status": by_path, "same_figures": figures(path_lines) == figures(name_lines),
                "recall": _line(path_lines, "recall          :"), "name_status": by_name}


# ---- neutralisations -------------------------------------------------------------------

def key_read_from_corpora():
    """--key read as the old scorer read every key: benchmark/corpora/<bundle name>/."""
    sc = _scorer()
    return patch.object(sc, "_read_key_file", lambda path: sc._load_key(Path(path).parent.name))


def twin_options_ignored():
    """--twin-key and --twin-run accepted and dropped."""
    return patch.object(_scorer(), "explicit_twin", lambda key, twin_key, twin_run: None)


def twin_taken_unchecked():
    """The twin named by path taken as given: no pairing check, no document check."""
    sc = _scorer()
    return patch.object(sc, "explicit_twin", lambda key, twin_key, twin_run: (
        sc._load_bus_findings(twin_run), str(twin_run), str(key.get("twin_of") or "")))


def default_path_treated_as_by_path():
    """--corpus loses its twin lookup under output/runs/, as if every key were read by path."""
    sc = _scorer()
    real = sc._print_twin_check
    return patch.object(sc, "_print_twin_check",
                        lambda corpus, key, findings, twin=None, by_path=False:
                        real(corpus, key, findings, twin, by_path=True))


def corpus_must_be_a_name():
    """--corpus refused unless it is a plain name (plan revision R5, overruled by R21):
    the absolute path tools/cloud_run_remote.py passes would no longer score."""
    sc = _scorer()
    real = sc._load_key

    def plain_only(corpus):
        if Path(corpus).name != str(corpus):
            raise SystemExit("--corpus must be a plain name: %s" % corpus)
        return real(corpus)
    return patch.object(sc, "_load_key", plain_only)


class ScorerPathChecks(unittest.TestCase):
    evidence = []

    @classmethod
    def setUpClass(cls):
        if not (GEN / "generate.py").is_file():
            raise unittest.SkipTest("benchmark/generators/ is not in this tree")

    def prove(self, name, observe, expected, neutralise):
        result = prove_effect(name=name, validate=lambda: SCORER.is_file() and REMOTE.is_file(),
                              observe=observe,
                              check=lambda: ("PASS" if observe() == expected() else "FAIL", name),
                              neutralise=neutralise)
        ScorerPathChecks.evidence.append(result)

    def test_a_generated_bundle_is_scored_by_its_key_path(self):
        """Neutralised: --key read from benchmark/corpora/ as before: refused."""
        planted = len(_key(generate_once()["test"])["planted"])
        self.prove("key_by_path", observe_key_and_twin, lambda: expected_key_and_twin(planted),
                   key_read_from_corpora)

    def test_the_twin_is_compared_by_its_key_and_run_paths(self):
        """Neutralised: the twin options are accepted and dropped: no twin check."""
        planted = len(_key(generate_once()["test"])["planted"])
        self.prove("twin_by_path", observe_key_and_twin, lambda: expected_key_and_twin(planted),
                   twin_options_ignored)

    def test_a_twin_that_is_not_the_declared_twin_is_refused(self):
        """Neutralised: the named twin is taken unchecked: the wrong key and run compare."""
        self.prove("twin_pairing_checked", observe_wrong_twin, lambda: WRONG_TWIN, twin_taken_unchecked)

    def test_the_default_path_is_unchanged(self):
        """Neutralised: --corpus loses its output/runs/ twin lookup."""
        planted = len(_key(generate_once()["test"])["planted"])
        expected = lambda: {"status": 0, "recall": expected_key_and_twin(planted)["recall"],
                            "twin": expected_key_and_twin(planted)["twin"]}
        self.prove("default_path_unchanged", observe_default_path, expected, default_path_treated_as_by_path)

    def test_the_absolute_path_caller_is_unchanged(self):
        """Neutralised: --corpus refused unless a plain name (R5's proposal)."""
        planted = len(_key(generate_once()["test"])["planted"])
        expected = lambda: {"flags": ["--corpus", "--run"], "status": 0, "same_figures": True,
                            "recall": expected_key_and_twin(planted)["recall"], "name_status": 0}
        self.prove("absolute_caller_unchanged", observe_absolute_caller, expected, corpus_must_be_a_name)


_GENERATED = {}


def generate_once():
    """One generation kept for the expected figures (planted counts); the observations
    generate their own, each in its own temporary folder."""
    if "bundles" not in _GENERATED:
        _GENERATED["dir"] = tempfile.TemporaryDirectory(prefix="shimmer_scorer_expected_")
        _GENERATED["bundles"] = generate(Path(_GENERATED["dir"].name))
    return _GENERATED["bundles"]


def check():
    ScorerPathChecks.evidence = []
    suite = unittest.defaultTestLoader.loadTestsFromTestCase(ScorerPathChecks)
    result = unittest.TestResult()
    try:
        suite.run(result)
    finally:
        if "dir" in _GENERATED:
            _GENERATED.pop("dir").cleanup()
            _GENERATED.clear()
    if not result.wasSuccessful():
        problems = [str(case).split(" ")[0] + ": " + str(err).strip().splitlines()[-1][:160]
                    for case, err in list(result.failures) + list(result.errors)]
        return "FAIL", "; ".join(problems[:4])
    if result.skipped:
        return "SKIP", "scorer path checks skipped: %s" % result.skipped[0][1]
    return "PASS", ("%d proofs, each neutralise, fail, restore, pass: a test generated by "
                    "benchmark/generators (f3, seed 7, into a temporary folder) is scored by --key, its "
                    "twin compared by --twin-key and --twin-run and scored the other way round; a twin key "
                    "that is not the declared twin and a run that is not of the twin's document are "
                    "refused; --corpus with a name still finds the twin's run under output/runs/; the "
                    "flags tools/cloud_run_remote.py passes, run with an absolute bundle path, give the "
                    "same figures as the name" % result.testsRun)


def main():
    status, detail = check()
    for proof in ScorerPathChecks.evidence:
        print(proof["name"], proof["status"])
        print("  before:  ", json.dumps(proof["before"], sort_keys=True)[:400])
        print("  mutated: ", json.dumps(proof["mutated"], sort_keys=True)[:400])
        print("  restored:", json.dumps(proof["restored"], sort_keys=True)[:400])
    print(status, detail)
    return 0 if status == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
