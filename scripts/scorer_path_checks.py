"""Gate check: the scorer reads a key and a twin by path (loop S5, R21, item 0.10, DS5-7).

tools/score_corpus.py used to read keys only from benchmark/corpora/<name>/ and to look
for a twin's run only under output/runs/ (open items 17 and 23), so a generated
development bundle could not be scored. It now takes --key (a key file anywhere) and
--twin-key with --twin-run (the twin's key and a run of the twin, anywhere), and keeps
--corpus exactly as it was, the absolute path tools/cloud_run_remote.py passes included.

Every case EXECUTES the scorer's main() on files written into temporary folders:

1. a test generated by benchmark/generators (family f3, fixed seed 7, through the
   generator's own command line in a separate process started with -B, into a temporary
   folder, never into the repository) is scored by --key on a fixture run folder that
   holds Python findings for every planted entry and one model sentence;
2. its twin is compared through --twin-key and --twin-run (the same model sentence on a
   fixture run of the twin is reported as worded identically in both twins), and the
   twin itself is scored by --key with the test as its twin;
3. a twin key that is not the declared twin, and a twin run that is not a run of the
   twin's document, are refused, not compared;
4. the default path is unchanged: --corpus <name> under a temporary corpora root finds
   the twin's run under output/runs/ exactly as before;
5. the absolute-path caller is unchanged: the flags tools/cloud_run_remote.py passes to
   the scorer are read from its source and run with an absolute bundle path, and give
   the same figures as the name.

Each is proven by neutralise, fail, restore, pass (scripts/effect_proof.py). No model,
no pipeline run, no provider, no network. SKIP when benchmark/generators/ is absent (the
container image does not ship it).
"""
