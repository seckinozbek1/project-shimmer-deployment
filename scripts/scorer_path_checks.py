def _scorer():
    import score_corpus
    return score_corpus


def generate(out):
    """The generator's own command line, one test, fixed family and seed, into `out`.
    Returns {"test": folder, "twin": folder, "probe": folder}."""
    subprocess.run([sys.executable, "-B", "-X", "utf8", str(GEN / "generate.py"), "one", FAMILY,
                    str(SEED), "--out", str(out)], check=True, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL, cwd=str(out))
    found = {}
    for key_path in sorted(Path(out).glob("*/*/answer_key.json")):
        key = json.loads(key_path.read_text(encoding="utf-8"))
        if key.get("twin_of"):
            found["test" if key.get("planted") else "twin"] = key_path.parent
        elif key.get("probe") and "probe" not in found:
            found["probe"] = key_path.parent
    if set(found) != {"test", "twin", "probe"}:
        raise AssertionError("the generated test has no test, twin and probe: %s" % sorted(found))
    return found


def _key(folder):
    return json.loads((Path(folder) / "answer_key.json").read_text(encoding="utf-8"))


def write_run(run, document, items):
    """A fixture run folder: one bus post per writer, and the deliverable folder named
    after the document, which is how a run says which document it reviewed."""
    stem = document.rsplit(".", 1)[0]
    (run / "logs").mkdir(parents=True)
    (run / "deliverables" / stem).mkdir(parents=True)
    lines = []
    for backend, model, posted in items:
        lines.append(json.dumps({"sender": "fixture", "body": {
            "event": "AGENT_OUTPUT", "backend": backend, "model": model,
            "payload": {"agent": "fixture", "doc_id": stem, "items": posted}}}))
    (run / "logs" / "agent_bus.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (run / "deliverables" / stem / "review_data.json").write_text(
        json.dumps({"amendments": []}), encoding="utf-8")
    return run


def model_sentence(unit):
    return {"relation": "missing_field", "record_verdict": "irregular", "unit_id": unit,
            "rule_id": "CONV-X", "explanation": SHARED_SENTENCE}


def python_findings(key):
    out = []
    for entry in key.get("planted") or []:
        claim = entry.get("claim") or {}
        out.append({"relation": entry.get("relation") or claim.get("relation"),
                    "record_verdict": "irregular", "unit_id": entry["unit"],
                    "rule_id": entry["rule"], "field_label": claim.get("field_label"),
                    "value_a": claim.get("value_a"), "value_b": claim.get("value_b")})
    return out


def fixture(root):
    """The generated test, its twin, a probe, and a fixture run of each of the first two."""
    root = Path(root)
    (root / "generated").mkdir()
    bundles = generate(root / "generated")
    test, twin = _key(bundles["test"]), _key(bundles["twin"])
    clean_unit = (twin.get("clean") or ["u01"])[0]
    runs = {
        "test": write_run(root / "runs" / "run_test", test["document"],
                          [("paired", "python", python_findings(test)),
                           ("cloud", "fixture-model", [model_sentence(clean_unit)])]),
        "twin": write_run(root / "runs" / "run_twin", twin["document"],
                          [("cloud", "fixture-model", [model_sentence(clean_unit)])]),
    }
    return bundles, runs


def run_scorer(argv):
    """main() on argv: (exit status or refusal text, printed lines)."""
    sc = _scorer()
    out = io.StringIO()
    saved_path = list(sys.path)  # the scorer inserts its ROOT/scripts; a patched ROOT is temporary
    try:
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
            status = sc.main(argv)
    except SystemExit as exc:
        status = "refused: %s" % (exc.code if isinstance(exc.code, str) else "usage")
    finally:
        sys.path[:] = saved_path
    return status, out.getvalue().splitlines()


def figures(lines):
    """The lines that carry a figure, with every path and run label taken out."""
    keep = []
    for line in lines:
        head = line.split(":", 1)[0].strip()
        if head in ("corpus", "run"):
            continue
        if line.startswith("twin check"):
            line = re.sub(r"\(([^()]*)\)\s*$", "(run)", line)
        keep.append(line.rstrip())
    return keep


def _line(lines, start):
    return next((ln for ln in lines if ln.startswith(start)), "")


