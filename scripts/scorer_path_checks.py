ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "benchmark" / "generators"
SCORER = ROOT / "tools" / "score_corpus.py"
REMOTE = ROOT / "tools" / "cloud_run_remote.py"
FAMILY, SEED = "f3", 7
SHARED_SENTENCE = "The section does not state who prepared it."

for _path in (str(ROOT / "scripts"), str(ROOT / "tools")):
    if _path not in sys.path:
        sys.path.insert(0, _path)

