"""Deterministic prospective registration, cohort and blank reviewer exports."""
from pathlib import Path
import json
import shutil
import zipfile
import registration as r


def archive(folder,path):
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED) as z:
        for p in sorted(Path(folder).iterdir()):
            if not p.is_file() or p.is_symlink():raise ValueError('Unexpected export entry')
            info=zipfile.ZipInfo(p.name,(1980,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0o100644<<16
            z.writestr(info,p.read_bytes())


def main():
    r.h.verify_baseline();r.h.verify_freeze()
    if (r.HERE/'freeze.json').exists():r.verify_frozen()
    rows=r.records();first,second=r.selection(rows);index={x['example_id']:x for x in rows}
    selected=[index[i] for i in first];double=[index[i] for i in second]
    if len({x['document_family'] for x in selected})!=80:raise ValueError('Maximum document-family coverage not reached')
    if len({x['template_family'] for x in selected})!=16:raise ValueError('Template coverage incomplete')
    if sum(x['split'] in ('test','sealed_adversarial') for x in selected)<64:raise ValueError('Unseen template coverage insufficient')
    r.write(r.HERE/'acceptance_registration.json',r.profile())
    r.write(r.HERE/'cohort.json',dict(profile=r.VERSION,ids=first,composition=r.composition(selected)))
    r.write(r.HERE/'double_review.json',dict(profile=r.VERSION,ids=second,composition=r.composition(double)))
    r.write(r.HERE/'evaluation_population.json',dict(profile=r.VERSION,
        ids=[i for i in first if index[i]['split']!='train'],
        scope='Selected DEV/TEST/public adversarial only. Requires accepted independent labels; never treat TRAIN predictions as generalization evidence.'))
    r.write(r.HERE/'selection_metadata.json',dict(seed=r.SEED,algorithm=r.select.__doc__,source_benchmark=r.h.VERSION,
        source_freeze_sha256=r.digest((r.h.HERE/'freeze.json').read_bytes()),unique_examples=192,mandatory_held_out=72,
        maximum_available_document_families=80,achieved_document_families=80,first_role_target={'producer':96,'auditor':96},
        double_role_target={'producer':24,'auditor':24},remaining_unselected=544,
        independent_claim='Families share templates and authored construction; family counts do not assert human independence.'))
    manifests={}
    for name,ids in [('reviewer_1_first_tuning_v1',first),('reviewer_2_first_tuning_v1',second)]:
        folder=r.HERE/name;folder.mkdir(exist_ok=True)
        packet_ids=[r.h.packet(index[i])['packet_id'] for i in ids]
        expected={'INSTRUCTIONS.md'}|{p+suffix for p in packet_ids for suffix in ('.json','.md')}
        # This directory is generated by this task; reject unknown content
        # rather than deleting a user's files or packaging it accidentally.
        if any(p.name not in expected for p in folder.iterdir()):raise ValueError('Unapproved existing reviewer export file')
        shutil.copyfile(r.HERE/'reviewer_instructions.md',folder/'INSTRUCTIONS.md')
        for ident in packet_ids:
            for suffix in ('.json','.md'):shutil.copyfile(r.h.HERE/'review_packets'/(ident+suffix),folder/(ident+suffix))
        r.audit_export(folder,packet_ids)
        archive(folder,r.HERE/(name+'.zip'))
        manifests[name]=dict(packet_ids=packet_ids,files={p.name:r.digest(p.read_bytes()) for p in sorted(folder.iterdir())},
            archive_sha256=r.digest((r.HERE/(name+'.zip')).read_bytes()))
    r.write(r.HERE/'export_admin_manifest.json',manifests)
    coverage=r.review_coverage(rows,first,second,r.HERE/'no_submissions_exist')
    r.write(r.HERE/'training_access_template.json',r.eligible_training(rows,coverage))
    r.write(r.HERE/'reviewer_registry.template.json',dict(reviewers={},
        instruction='Operator supplies verified independent human IDs with human=true, operator_verified=true, independent_of_authorship=true, is_operator=false. No pre-approved identities.'))
    r.write(r.HERE/'readiness.json',{k:v for k,v in coverage.items() if k!='accepted_targets'})
    files=[p for p in r.HERE.rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.name!='freeze.json']
    r.write(r.HERE/'freeze.json',dict(profile=r.VERSION,hashes={p.relative_to(r.HERE).as_posix():r.digest(p.read_bytes()) for p in sorted(files)}))
    print(json.dumps(dict(first=r.composition(selected),second=r.composition(double))))


if __name__=='__main__':main()
